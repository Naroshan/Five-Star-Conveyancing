// One-off generator: reads the researched real-town CSV and produces
// src/lib/locationsGenerated.ts. Not run at build time — its output is
// committed. Re-run manually only if the source CSV changes.
import fs from "node:fs";

const CSV_PATH = process.argv[2];
if (!CSV_PATH) {
  console.error("Usage: node generate-locations.mjs <path-to-csv>");
  process.exit(1);
}

// City names already hand-written in locations.ts — excluded here so their
// bespoke intros aren't overwritten by a generated duplicate.
const EXISTING_CITIES = new Set([
  "london", "manchester", "birmingham", "leeds", "cardiff", "bristol",
  "liverpool", "sheffield", "newcastle upon tyne", "nottingham", "swansea",
]);

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/'/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

const raw = fs.readFileSync(CSV_PATH, "utf8");
const lines = raw.split("\n").map((l) => l.trim()).filter(Boolean);

const seenCity = new Set();
const seenSlug = new Set();
const entries = [];

for (const line of lines) {
  const [city, county, jurisdiction] = line.split(",");
  if (!city || !county || !jurisdiction) continue;
  const cityKey = city.toLowerCase();
  if (EXISTING_CITIES.has(cityKey)) continue;
  if (seenCity.has(cityKey)) continue; // duplicate row for the same town
  seenCity.add(cityKey);

  let slug = slugify(city);
  if (seenSlug.has(slug)) {
    slug = `${slug}-${slugify(county)}`;
  }
  seenSlug.add(slug);

  entries.push({ slug, city, county, jurisdiction });
}

entries.sort((a, b) => a.city.localeCompare(b.city));

const out = `// Auto-generated by scripts/generate-locations.mjs — do not hand-edit.
// Source: a real, verified list of UK towns gathered county-by-county via
// web search (see project notes). Regenerate by re-running the script
// against an updated CSV rather than editing this file directly.
import type { GeneratedLocation } from "./locations";

export const GENERATED_LOCATIONS: GeneratedLocation[] = [
${entries.map((e) => `  { slug: ${JSON.stringify(e.slug)}, city: ${JSON.stringify(e.city)}, county: ${JSON.stringify(e.county)}, jurisdiction: ${JSON.stringify(e.jurisdiction)} },`).join("\n")}
];
`;

fs.writeFileSync(new URL("../src/lib/locationsGenerated.ts", import.meta.url), out);
console.log(`Wrote ${entries.length} generated locations.`);
